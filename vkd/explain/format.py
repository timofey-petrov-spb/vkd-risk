"""Русская запись чисел для объяснений, текстов правила, экрана и выгрузки: запятая,
·10^n, единица после числа.

ЕДИНОЕ ПРАВИЛО. Раньше порог степенной записи стоял числом по месту в двух функциях
(здесь и в app/ui.fmt) и был равен 1e5. Из-за этого одна и та же величина печаталась
на одном экране двумя способами: «флюенс ниже (88701 против 2,22·10^6 част./см²)» —
голое пятизначное число рядом со степенной записью, сопоставить их глазом нечем
(находка девятого круга). Порог опущен до 1e4 и вынесен константой SCI_MIN: любая
величина от десяти тысяч печатается степенью, и столбец флюенса выглядит одинаково
во всех местах — в тексте правила, в карточках, в отчёте выгрузки.
"""
from __future__ import annotations

# Границы степенной записи. Обе — правило оформления, а не физика: за ними стоит
# читаемость колонки чисел, и менять их нужно ЗДЕСЬ, разом для ядра, экрана и выгрузки.
SCI_MIN = 1e4        # от 10 000 и выше — «8,87·10^4»
SCI_MAX_SMALL = 1e-2  # меньше 0,01 по модулю — «5,64·10^-7»
FIXED_INT = 100.0     # от 100 до SCI_MIN — целое без дробной части


def fmt_ru(v, unit: str = '') -> str:
    """Число по-русски: запятая, порядок в виде «10^n» (надстрочные цифры ставит экран).
    Безразмерная единица «1» не печатается — её печать превращала «Kp 5 1» в загадку."""
    if v is None:
        return '—'
    if isinstance(v, float):
        if v == 0:
            s = '0'
        elif abs(v) >= SCI_MIN or abs(v) < SCI_MAX_SMALL:
            m, e = ('%.2e' % v).split('e')
            s = '%s·10^%d' % (m.replace('.', ','), int(e))
        elif abs(v) >= FIXED_INT:
            s = '%.0f' % v
        else:
            s = ('%.2f' % v).rstrip('0').rstrip('.').replace('.', ',')
    else:
        s = str(v)
    return s + (' ' + unit if unit and unit not in ('1',) else '')


