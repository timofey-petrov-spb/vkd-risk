# ================================================================== контраст, считаем числами

def _channels(color: str) -> tuple[int, int, int]:
    """«#rrggbb» → три составляющих 0…255."""
    s = color.lstrip('#')
    if len(s) != 6:
        raise ValueError('цвет задаётся как #rrggbb, получено: %r' % (color,))
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def _to_linear(value: int) -> float:
    """Снять гамму sRGB. Формула и порог 0,04045 — IEC 61966-2-1, она же в WCAG 2.1."""
    c = value / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def relative_luminance(color: str) -> float:
    """Относительная яркость по WCAG 2.1: 0,2126·R + 0,7152·G + 0,0722·B по снятым гаммам."""
    r, g, b = (_to_linear(v) for v in _channels(color))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(one: str, other: str) -> float:
    """Отношение контраста двух цветов, (L_светлее + 0,05) / (L_темнее + 0,05)."""
    a, b = relative_luminance(one), relative_luminance(other)
    return (max(a, b) + 0.05) / (min(a, b) + 0.05)


def blend(front: str, alpha: float, back: str) -> str:
    """Цвет, который получится, если положить `front` с непрозрачностью `alpha` на `back`.

    Это то самое, что делает браузер с непрозрачным кругом на непрозрачном фоне, поэтому
    наихудший фон под текстом можно посчитать, а не оценить на глаз.
    """
    if not 0.0 <= alpha <= 1.0:
        raise ValueError('непрозрачность вне 0…1: %r' % (alpha,))
    f, b = _channels(front), _channels(back)
    return '#%02x%02x%02x' % tuple(round(b[i] + alpha * (f[i] - b[i])) for i in range(3))


# Запас на округление композиции браузером. Замер в Chromium (круг первого класса нарисован на
# холсте 1 600 × 900 поверх заливки #0e1117, пиксель сердцевины прочитан из холста) дал #36393f
# при расчётных по формуле #35383e — на один уровень светлее по каждой составляющей. Расхождение
# меньше кванта яркости, но контраст обязан считаться по НАБЛЮДАЕМОМУ пикселю, а не по модели,
# поэтому к расчёту добавляется один уровень. Тот же замер показал, что самый светлый пиксель
# ВСЕГО поля равен сердцевине одиночной звезды первого класса: наложений нет, как и обещает
# MIN_SEPARATION, и складывать непрозрачности не приходится.
ROUNDING_GUARD = 1


def brightest_star_background() -> str:
    """Наихудший фон, который создаёт этот модуль: сердцевина самой яркой звезды на фоне страницы."""
    computed = _channels(blend(INK, MAGNITUDE_CLASSES[0][2], BG))
    return '#%02x%02x%02x' % tuple(min(255, v + ROUNDING_GUARD) for v in computed)


def highlight_background() -> str:
    """Фон изменившейся ячейки приборной полосы в первый момент подсветки."""
    return LINE


def contrast_table() -> list[tuple[str, str, str, float]]:
    """Все пары «текст — фон», которые создаёт модуль: подпись, цвет текста, цвет фона, отношение.

    Проверяются три фона: чистый фон страницы, сердцевина самой яркой звезды и подсветка
    изменившейся ячейки. Других фонов модуль не создаёт: блоки рекомендации и панелей
    непрозрачны и закрывают небо полностью.
    """
    rows: list[tuple[str, str, str, float]] = []
    for caption, background in (('фон страницы', BG),
                                ('сердцевина самой яркой звезды', brightest_star_background()),
                                ('подсветка изменившейся ячейки', highlight_background())):
        for name, tone in TEXT_TONES:
            rows.append(('%s на фоне «%s»' % (name, caption), tone, background,
                         contrast_ratio(tone, background)))
    return rows


# ================================================================== поле звёзд

def magnitude_counts(total: int = STAR_COUNT) -> tuple[int, ...]:
    """Сколько звёзд приходится на каждый класс яркости.

    Доли берутся из закона N(ярче m) ∝ 10^(0,6·m) (см. COUNT_RATIO_LG). Остаток от округления
    вниз раздаётся по наибольшим дробным частям, поэтому сумма ровно равна `total`.

    Непустоту классов раздача остатка НЕ гарантирует: при малом `total` самый яркий класс может
    получить ноль. Тогда функция падает, а не отдаёт поле без ярких звёзд молча — расчёт
    контраста опирается на то, что звезда первого класса на поле есть. На рабочем `total = 140`
    выходит 2 / 7 / 26 / 105.
    """
    cumulative = [10 ** (COUNT_RATIO_LG * m) for m, _r, _a in MAGNITUDE_CLASSES]
    previous = [1.0] + cumulative[:-1]        # 10^0 = 1 — «ярче нулевой величины»
    per_class = [c - p for c, p in zip(cumulative, previous)]
    scale = total / sum(per_class)
    exact = [v * scale for v in per_class]
    counts = [int(math.floor(v)) for v in exact]
    remainder = total - sum(counts)
    # Раздаём остаток тем классам, у кого дробная часть больше; при равенстве — более яркому
    # классу (меньший индекс), чтобы результат не зависел от устойчивости сортировки.
    order = sorted(range(len(exact)), key=lambda i: (-(exact[i] - counts[i]), i))
    for i in order[:remainder]:
        counts[i] += 1
    if any(c <= 0 for c in counts):
        raise RuntimeError('на класс яркости пришлось ноль звёзд при total=%d: %r' % (total, counts))
    return tuple(counts)


@lru_cache(maxsize=4)
def stars(seed: int = STAR_SEED, total: int = STAR_COUNT) -> tuple[Star, ...]:
    """Поле звёзд, одно и то же при одном и том же зерне.

    Точки ставятся отбором: кандидат принимается, только если он не ближе MIN_SEPARATION к уже
    поставленным. Яркие классы ставятся первыми — им достаётся более свободное поле, и две
    крупные звёзды заведомо не оказываются рядом.

    Датчик — `random.Random(seed)` из стандартной библиотеки: вихрь Мерсенна воспроизводится
    между запусками и машинами, поэтому картинка проверяется тестом на точные координаты.
    """
    rng = random.Random(seed)
    placed: list[Star] = []
    squared_gap = MIN_SEPARATION * MIN_SEPARATION
    for (magnitude, _radius, _alpha), count in zip(MAGNITUDE_CLASSES, magnitude_counts(total)):
        for _ in range(count):
            for _attempt in range(MAX_PLACEMENT_ATTEMPTS):
                x = rng.randrange(FIELD_MARGIN, FIELD_W - FIELD_MARGIN)
                y = rng.randrange(FIELD_MARGIN, FIELD_H - FIELD_MARGIN)
                if all((x - s.x) ** 2 + (y - s.y) ** 2 >= squared_gap for s in placed):
                    placed.append(Star(x, y, magnitude))
                    break
            else:
                raise RuntimeError(
                    'звезда %d из %d не встала за %d попыток при расстоянии %d на поле %d×%d: '
                    'поле переполнено, уменьшите STAR_COUNT или MIN_SEPARATION'
                    % (len(placed) + 1, total, MAX_PLACEMENT_ATTEMPTS, MIN_SEPARATION, FIELD_W, FIELD_H))
    return tuple(placed)


def _trim_number(value: float) -> str:
    """0,8 → «.8»; 1,70 → «1.7». Короче на пару знаков в каждой звезде, а их сто сорок.

    Точка здесь — не десятичный разделитель на экране, а синтаксис SVG; правило про запятую
    относится к тексту, который читает человек.
    """
    text = ('%.3f' % value).rstrip('0').rstrip('.')
    return text[1:] if text.startswith('0.') else text


def starfield_svg(seed: int = STAR_SEED, total: int = STAR_COUNT) -> str:
    """Картинка неба: один SVG, звёзды сгруппированы по классам яркости.

    Группировка по классам — не украшение, а вес: цвет и непрозрачность записаны один раз на
    группу, и в каждой звезде остаются только три числа. Без группировки разметка тяжелее
    примерно вдвое.

    `preserveAspectRatio='xMidYMid slice'` вместе с `background-size: cover` означает: на экране
    другого соотношения сторон поле ОБРЕЗАЕТСЯ по краям и остаётся отцентрированным. Растяжения
    нет, поэтому круги нигде не становятся эллипсами.
    """
    by_magnitude: dict[int, list[Star]] = {}
    for star in stars(seed, total):
        by_magnitude.setdefault(star.magnitude, []).append(star)
    parts = ["<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 %d %d' "
             "preserveAspectRatio='xMidYMid slice'><g fill='%s'>" % (FIELD_W, FIELD_H, INK)]
    for magnitude, radius, alpha in MAGNITUDE_CLASSES:
        group = by_magnitude.get(magnitude, ())
        if not group:
            continue
        parts.append("<g opacity='%s'>" % _trim_number(alpha))
        radius_text = _trim_number(radius)
        for star in group:
            parts.append("<circle cx='%d' cy='%d' r='%s'/>" % (star.x, star.y, radius_text))
        parts.append('</g>')
    parts.append('</g></svg>')
    return ''.join(parts)


def _data_uri(svg: str) -> str:
    """SVG внутри url(). Кодируются только те знаки, которые ломают разбор CSS или адреса.

    Кавычки внутри картинки одинарные, поэтому url("…") закрывается там, где положено.
    Знак решётки обязателен к кодированию: в адресе он начинает часть после решётки, и
    незакодированный цвет «#e8ebf2» обрезал бы картинку на первой же группе.
    """
    encoded = (svg.replace('%', '%25').replace('#', '%23')
                  .replace('<', '%3C').replace('>', '%3E')
                  .replace('"', '%22').replace('\n', ''))
    return 'data:image/svg+xml,' + encoded


# ================================================================== стили

def _starfield_css(seed: int = STAR_SEED, total: int = STAR_COUNT) -> str:
    """Правила самого неба."""
    # Небо — СОБСТВЕННЫЙ фон `.stApp`, а не отдельный слой поверх него. Так сделано по разбору
    # живой страницы, а не по общим соображениям:
    #   * `.stApp` у Streamlit — это `position: absolute` с `overflow: hidden`, ровно по видимой
    #     области, и он НЕ прокручивается: прокрутка живёт внутри, в `section.stMain`. Значит
    #     небо стоит на месте само по себе, без `position: fixed` и без псевдоэлемента;
    #   * фон элемента по правилам CSS рисуется ниже ВСЕХ его потомков, поэтому ни `z-index`,
    #     ни контекст наложения тут не нужны и ломаться нечему;
    #   * все узлы от `.stApp` до `.block-container` прозрачны — это замерено на странице, а не
    #     предположено, — так что небо видно насквозь. Боковая панель непрозрачна по стилям
    #     app/ui.py и небо закрывает; так и надо, рабочая панель должна быть сплошной.
    #
    # Первая редакция ставила небо на `.stApp::before` и ради `z-index: -1` объявляла
    # `.stApp { position: relative }`. На живой странице это отняло у `.stApp` абсолютное
    # позиционирование, его высота стала нулевой, и `overflow: hidden` срезал ВСЁ содержимое
    # страницы: остались одни звёзды. Ошибка поймана проверкой в браузере, не рассуждением.
    #
    # Селектор по data-testid, а не только по классу: его весомость выше, чем у
    # `.stApp { background: var(--bg) }` в app/ui.py, поэтому сокращённая запись `background`
    # оттуда не обнулит картинку, в каком бы порядке ни печатались два набора стилей. Цвет
    # заливки при этом остаётся от app/ui.py и от .streamlit/config.toml — он не переопределён.
    #
    # ВТОРОЕ ПРАВИЛО, про пустой контейнер. Печать блока стилей создаёт контейнер элемента
    # нулевой высоты, но вертикальная раскладка Streamlit всё равно отсчитывает от него отступ
    # в 16 пикселей, и подключение фона добавило бы на страницу 16 пикселей пустоты ни за чем.
    # Прячется КАЖДЫЙ ПОСЛЕДУЮЩИЙ такой контейнер, а не всякий: первый оставлен на месте,
    # потому что он уже есть на странице (его печатает app/ui.py) и раскладка выстроена с ним.
    # Поэтому подключение фона не двигает страницу ВООБЩЕ. Замерено в браузере: заголовок стоит
    # на 67 пикселях от верха окна и с фоном, и без него; правило, прятавшее ОБА контейнера,
    # поднимало его до 51 и загоняло под верхнюю полосу Streamlit высотой 60. Спрятать что-то
    # видимое правило не может: `style:only-child` означает, что в контейнере нет ничего, кроме
    # блока стилей.
    #
    # Пояснения держатся здесь, а не внутри самих правил: комментарий в CSS уходит в браузер
    # при каждой отрисовке, а читают его разработчики. В разметке остаются короткие пометки.
    return (
        'div[data-testid="stApp"], .stApp {\n'
        '        background-image:url("%(uri)s");\n'
        '        background-repeat:no-repeat; background-position:center center; background-size:cover; }\n'
        '/* лишний отступ от второго блока стилей */\n'
        '%(container)s ~ %(container)s { display:none; }\n'
        '/* на бумагу небо не идёт */\n'
        '@media print { div[data-testid="stApp"], .stApp { background-image:none; } }\n'
    ) % {'uri': _data_uri(starfield_svg(seed, total)), 'container': STYLE_ONLY_CONTAINER}


def _animation_css() -> str:
    r"""Три анимации и выключатель по системной настройке.

    Пояснения держатся ЗДЕСЬ, а не внутри правил: комментарий в CSS уходит в браузер при каждой
    отрисовке, а читают его разработчики. В разметке остаются короткие пометки.

    1. ПРОЯВЛЕНИЕ БЛОКА РЕКОМЕНДАЦИИ, 0,25 с, один проход. Означает «вот ответ на твой вопрос»:
       блок приходит снизу на шесть пикселей и проявляется. Тот же приём у блока вердикта в
       разборе конкретных окон — это тот же по смыслу блок ответа.
       Замерено на живой странице: при ПЕРЕСЧЁТЕ проявление не повторяется вовсе — три нажатия
       кнопки дали ноль запусков, потому что Streamlit оставляет тот же узел и меняет только
       текст внутри. То есть блок проявляется, когда он действительно появляется, и не мигает
       при каждом действии человека. Это и требовалось: движение означает событие, а не
       украшает.

    2. ОТРИСОВКА ЛЕНТЫ ОКОН слева направо, 0,4 с, один проход. Ось ленты — время начала выхода,
       поэтому раскрытие слева направо идёт ВДОЛЬ оси и читается как «сервис прошёл срок поиска
       от начала к концу»; вместе с лентой проявляется и полоса рекомендованного промежутка на
       ней. Цепляется за класс `st-key-lenta_okon`, который Streamlit вешает на контейнер
       элемента с ключом (проверено на живой странице); второй ход, `.vk-draw`, оставлен на
       случай, если ленту обернут вручную.
       Заливка `backwards`, а не `both`: при `both` конечное `clip-path: inset(0 0 0 0)`
       осталось бы на элементе НАВСЕГДА и обрезало бы подсказки Plotly, выходящие за рамку
       рисунка. С `backwards` после отрисовки `clip-path` снова `none` — замерено.

    3. ПОДСВЕТКА ИЗМЕНИВШЕЙСЯ ЯЧЕЙКИ приборной полосы, 0,9 с, один проход. Цвет — разделитель
       --line: он бесцветный и ничего не означает, тогда как любой из четырёх тонов
       происхождения сказал бы о ячейке неправду. Класс ставит mark_changed_cells(); без неё
       правило ни к чему не применяется.

    Системная настройка «уменьшить движение» выключает все три целиком: человеку, который её
    включил, движение мешает, а не нравится меньше. Небо при этом остаётся — оно статично и
    движением не является.
    """
    return r"""
/* 1. появление блока рекомендации */
@keyframes vk-reveal { from { opacity:0; transform:translateY(6px); } to { opacity:1; transform:none; } }
.reco, .verdict { animation: vk-reveal %(reveal)ss ease-out 1 backwards; }

/* 2. отрисовка ленты окон вдоль оси времени */
@keyframes vk-draw { from { clip-path: inset(0 100%% 0 0); } to { clip-path: inset(0 0 0 0); } }
.st-key-%(key)s div[data-testid="stPlotlyChart"], .vk-draw {
        animation: vk-draw %(draw)ss ease-out 1 backwards; }

/* 3. подсветка изменившейся ячейки приборной полосы */
@keyframes vk-changed { from { background-color:%(line)s; } to { background-color:transparent; } }
.cell.vk-changed { animation: vk-changed %(highlight)ss ease-out 1 backwards; }

/* системная настройка «уменьшить движение»: движение гаснет, небо остаётся */
@media (prefers-reduced-motion: reduce) {
  .reco, .verdict,
  .st-key-%(key)s div[data-testid="stPlotlyChart"], .vk-draw,
  .cell.vk-changed { animation: none; }
}
""" % {'reveal': _trim_number(REVEAL_S), 'draw': _trim_number(DRAW_S),
       'highlight': _trim_number(HIGHLIGHT_S), 'key': LENTA_KEY, 'line': LINE}


def css(seed: int = STAR_SEED, total: int = STAR_COUNT) -> str:
    r"""Вся разметка модуля одной строкой, вместе с обрамляющим <style>.

    Строка с анимациями объявлена RAW (r"…"), и этот docstring — тоже. Причина: в CSS
    встречаются последовательности вида \25B8, а в обычной строке Python прочитал бы «\25»
    как ВОСЬМЕРИЧНЫЙ escape и подставил бы в разметку знак U+0015. Эта ошибка уже доходила до
    развёрнутого сервиса (см. комментарий к CSS в app/ui.py), поэтому правило держится во всех
    строках со стилями — и в тех, где таких последовательностей пока нет. Проверка —
    tests/test_backdrop.py: в разметке нет знаков вне печатного диапазона.
    """
    return '<style>\n' + _starfield_css(seed, total) + _animation_css() + '</style>\n'


def weight_bytes(seed: int = STAR_SEED, total: int = STAR_COUNT) -> int:
    """Вес добавляемой разметки в байтах UTF-8 — то, что реально уходит в ответ страницы."""
    return len(css(seed, total).encode('utf-8'))


def apply(st_module=None) -> int:
    """Подключение в одну строку. Печатает стили и возвращает их вес в байтах.

    Streamlit ввозится внутри, а не сверху файла: так модуль считается и проверяется тестами
    без запуска приложения. Замерено на том же стенде, что и остальные замеры проекта
    (Windows 11, Python 3.14): ввоз модуля 0,023 с, первая сборка разметки 0,0013 с,
    каждая следующая 0,00005 с (поле звёзд считается один раз и лежит в кеше). Против
    0,12–0,65 с, которые занимает сам расчёт окон, это ничто; ни numpy, ни plotly, ни
    streamlit модуль при ввозе не подтягивает — проверено.
    """
    if st_module is None:
        import streamlit as st_module  # noqa: PLC0415 — см. строку выше
    markup = css()
    weight = len(markup.encode('utf-8'))
    if weight > WEIGHT_LIMIT_BYTES:
        raise RuntimeError('фон весит %d байт при пределе %d' % (weight, WEIGHT_LIMIT_BYTES))
    st_module.markdown(markup, unsafe_allow_html=True)
    return weight


# ================================================================== подсветка изменившейся ячейки

# Разбор ячейки приборной полосы в том виде, в каком её печатает ui.panel(): класс вида
# «cell k-obs», затем метка, затем значение. Подпись (.cs) намеренно не сравнивается: там стоит
# давность, она меняется при каждом пересчёте, и подсвечивалась бы вся полоса целиком.
_CELL_RE = re.compile(
    r'<div class="cell (k-[a-z]+)"><div class="cl">(.*?)</div><div class="cv">(.*?)</div>',
    re.S)


def cells(html: str) -> list[tuple[str, str]]:
    """Ячейки приборной полосы как пары «метка, значение», в порядке печати."""
    return [(label, value) for _kind, label, value in _CELL_RE.findall(html)]


def _by_position(html: str) -> dict[tuple[str, int], str]:
    """Ячейки по ключу «метка и какая она по счёту среди одноимённых» → значение.

    Просто по метке сравнивать нельзя: полоса состоит из нескольких строк, и две ячейки в разных
    строках вполне могут называться одинаково. Словарь по одной метке оставил бы из них
    последнюю, и первая сравнивалась бы с чужим значением — то есть подсвечивалась бы ячейка,
    которая не менялась. Номер среди одноимённых это исключает.
    """
    seen: dict[str, int] = {}
    out: dict[tuple[str, int], str] = {}
    for label, value in cells(html):
        number = seen.get(label, 0)
        seen[label] = number + 1
        out[(label, number)] = value
    return out


def changed_labels(html_now: str, html_previous: str | None) -> list[str]:
    """Метки ячеек, значение которых отличается от предыдущего снимка полосы.

    Ячейка, которой в предыдущем снимке не было вовсе, изменившейся НЕ считается: она появилась,
    а появление — это не смена значения, и подсвечивать при первой отрисовке всю полосу было бы
    ровно тем мельтешением, которого требуется избежать.

    Одноимённые ячейки сравниваются по порядку, а не сваливаются в одну (см. _by_position).
    Если одноимённые ячейки изменились обе, метка встретится в ответе дважды — по разу на
    ячейку, а не один раз на имя.
    """
    if not html_previous:
        return []
    was = _by_position(html_previous)
    return [label for (label, number), value in _by_position(html_now).items()
            if (label, number) in was and was[(label, number)] != value]


def mark_changed_cells(html_now: str, html_previous: str | None) -> str:
    """Добавить класс `vk-changed` тем ячейкам, значение которых изменилось.

    Возвращает разметку полосы. Если предыдущего снимка нет, разметка возвращается как есть:
    сравнивать не с чем, и выдумывать «изменение» нечестно.

    Падает, если разметка похожа на приборную полосу, но не разбирается: значит в app/ui.py
    сменилась структура ячейки, и подсветка молча перестала бы работать. Молча — нельзя.
    """
    if 'class="cell' in html_now and not _CELL_RE.search(html_now):
        raise RuntimeError('разметка приборной полосы не разбирается: структура ячейки в '
                           'app/ui.py изменилась, и подсветка изменившихся ячеек больше не '
                           'находит ни метки, ни значения')
    if not html_previous:
        return html_now
    was = _by_position(html_previous)
    # Пометки ставятся по тому же ключу «метка и номер среди одноимённых», по которому считалось
    # изменение, поэтому при одинаковых метках подсвечивается именно изменившаяся ячейка.
    seen: dict[str, int] = {}

    def replace(match: re.Match) -> str:
        kind, label, value = match.group(1), match.group(2), match.group(3)
        number = seen.get(label, 0)
        seen[label] = number + 1
        key = (label, number)
        if key not in was or was[key] == value:
            return match.group(0)
        return ('<div class="cell %s vk-changed"><div class="cl">%s</div><div class="cv">%s</div>'
                % (kind, label, value))

    return _CELL_RE.sub(replace, html_now)
