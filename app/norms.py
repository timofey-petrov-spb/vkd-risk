from __future__ import annotations

import math

NOAA_S = [(1, 10.0, 'S1, слабая'), (2, 100.0, 'S2, умеренная'), (3, 1000.0, 'S3, сильная'),
          (4, 10000.0, 'S4, очень сильная'), (5, 100000.0, 'S5, экстремальная')]   # pfu, >=10 МэВ
NOAA_G = [(1, 5, 'G1'), (2, 6, 'G2'), (3, 7, 'G3'), (4, 8, 'G4'), (5, 9, 'G5')]         # Kp


def gost_215_limit_Sv(T_months: float) -> float:
    """ГОСТ 25645.215-85: G_н(T) = 0,05 + 4·(1 − exp(−T/72)), Зв. Сверено с таблицей стандарта, 8/8 строк."""
    return 0.05 + 4.0 * (1.0 - math.exp(-T_months / 72.0))


def gost_215_hourly_uSv(T_months: float) -> float:
    """Контрольная часовая: G_н(T)/(720·T), месяц = 720 ч (выведено по таблице стандарта)."""
    return gost_215_limit_Sv(T_months) / (720.0 * T_months) * 1e6


def s_level(p10_pfu: float | None) -> str:
    if p10_pfu is None:
        return 'нет данных'
    lvl = 'ниже S1'
    for n, thr, name in NOAA_S:
        if p10_pfu >= thr:
            lvl = name
    return lvl


